"""Interface and file utilities for the Voice-to-Voice AI Assistant."""

from pathlib import Path
from time import sleep

from whisper.tokenizer import LANGUAGES

from config import (
    APP_TITLE,
    COUNTDOWN_SECONDS,
    DIVIDER_WIDTH,
)


def print_banner() -> None:
    """Display the application title."""

    divider = "=" * DIVIDER_WIDTH

    print()
    print(divider)
    print(APP_TITLE.center(DIVIDER_WIDTH))
    print(divider)
    print()


def wait_for_user() -> None:
    """Wait for the user to begin a voice-assistant session."""

    input("Press ENTER to start the voice assistant...")


def countdown(seconds: int = COUNTDOWN_SECONDS) -> None:
    """Display a countdown before microphone recording begins.

    Args:
        seconds: Number of countdown seconds.

    Raises:
        ValueError: If the countdown duration is negative.
    """
    if seconds < 0:
        raise ValueError(
            "The countdown duration cannot be negative."
        )

    if seconds == 0:
        print()
        print("Speak now!")
        print()
        return

    print()
    print("Recording starts in...")
    print()

    for remaining in range(seconds, 0, -1):
        print(remaining)
        sleep(1)

    print()
    print("Speak now!")
    print()


