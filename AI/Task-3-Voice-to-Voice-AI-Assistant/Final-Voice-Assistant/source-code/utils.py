def save_text_file(
    text: str,
    file_path: Path,
) -> Path:
    """Save non-empty text to a UTF-8 file.

    Args:
        text: Text that will be saved.
        file_path: Destination text-file path.

    Returns:
        The path of the saved file.

    Raises:
        ValueError: If the supplied text is empty.
        OSError: If the destination cannot be prepared or written.
    """
    cleaned_text = text.strip()

    if not cleaned_text:
        raise ValueError(
            "Empty text cannot be saved."
        )

    file_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    file_path.write_text(
        cleaned_text + "\n",
        encoding="utf-8",
    )

    return file_path


def display_session_summary(
    *,
    recording_time: float,
    model_loading_time: float,
    transcription_time: float,
    llm_response_time: float,
    synthesis_time: float,
    playback_time: float,
    total_runtime: float,
    whisper_model: str,
    whisper_device: str,
    cohere_model: str,
    voice_name: str,
    language_name: str,
    transcript_character_count: int,
    response_character_count: int,
    recording_file: Path,
    transcript_file: Path,
    response_file: Path,
    response_audio_file: Path,
) -> None:
    """Display information about a completed assistant session.

    Args:
        recording_time: Time used to record microphone audio.
        model_loading_time: Time used to load Whisper.
        transcription_time: Time used to recognize speech.
        llm_response_time: Time used to generate the AI response.
        synthesis_time: Time used to generate response audio.
        playback_time: Time used to play the response audio.
        total_runtime: Total processing and playback time.
        whisper_model: Name of the active Whisper model.
        whisper_device: Processing device used by Whisper.
        cohere_model: Name of the Cohere model.
        voice_name: Name of the selected Windows speech voice.
        language_name: Detected spoken language.
        transcript_character_count: Number of transcript characters.
        response_character_count: Number of AI-response characters.
        recording_file: Path of the microphone recording.
        transcript_file: Path of the saved transcript.
        response_file: Path of the saved AI response.
        response_audio_file: Path of the generated response audio.
    """
    divider = "=" * DIVIDER_WIDTH

    print("Session Summary")
    print(divider)

    print("Processing Times")
    print(f"  Recording:          {recording_time:.2f} seconds")
    print(f"  Model Loading:      {model_loading_time:.2f} seconds")
    print(f"  Transcription:      {transcription_time:.2f} seconds")
    print(f"  LLM Response:       {llm_response_time:.2f} seconds")
    print(f"  Speech Synthesis:   {synthesis_time:.2f} seconds")
    print(f"  Audio Playback:     {playback_time:.2f} seconds")
    print(f"  Total Runtime:      {total_runtime:.2f} seconds")
    print()

    print("Models and Session")
    print(f"  Whisper Model:      {whisper_model}")
    print(f"  Whisper Device:     {whisper_device.upper()}")
    print(f"  Cohere Model:       {cohere_model}")
    print(f"  Speech Voice:       {voice_name}")
    print(f"  Language:           {language_name}")
    print(f"  Transcript Length:  {transcript_character_count} characters")
    print(f"  Response Length:    {response_character_count} characters")
    print()

    print("Generated Files")
    print(f"  Recording:          {recording_file}")
    print(f"  Transcript:         {transcript_file}")
    print(f"  AI Response:        {response_file}")
    print(f"  Response Audio:     {response_audio_file}")

    print(divider)