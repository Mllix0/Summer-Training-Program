def language_code_to_name(language_code: str) -> str:
    """Convert a Whisper language code into a readable name.

    Args:
        language_code: Language code returned by Whisper.

    Returns:
        A readable language name or the uppercase language code.
    """
    cleaned_code = language_code.strip().lower()

    if not cleaned_code or cleaned_code == "unknown":
        return "Unknown"

    language_name = LANGUAGES.get(cleaned_code)

    if language_name:
        return language_name.title()

    return cleaned_code.upper()


